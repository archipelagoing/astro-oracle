const assert=require('node:assert/strict');
require('../web/core.js');
const {resolveLocal,coordinates,placesFromResponse}=require('../web/birth.js');
const resolve=(d,t,z)=>resolveLocal(d,t,z).map(c=>c.iso);
assert.deepEqual(resolve('1990-06-15','14:30','America/New_York'),['1990-06-15T18:30:00.000Z']);
assert.deepEqual(resolve('2026-03-08','02:30','America/New_York'),[]);
assert.deepEqual(resolve('2026-11-01','01:30','America/New_York'),['2026-11-01T05:30:00.000Z','2026-11-01T06:30:00.000Z']);
assert.deepEqual(resolve('2026-04-05','01:45','Australia/Lord_Howe'),['2026-04-04T14:45:00.000Z','2026-04-04T15:15:00.000Z']);
assert.deepEqual(resolve('2026-10-04','02:15','Australia/Lord_Howe'),[]);
assert.deepEqual(resolve('2011-12-30','12:00','Pacific/Apia'),[]);
assert.deepEqual(resolve('2000-01-01','00:00:30','Asia/Kathmandu'),['1999-12-31T18:15:30.000Z']);
assert.deepEqual(resolve('2000-02-29','00:00','UTC'),['2000-02-29T00:00:00.000Z']);
assert.throws(()=>resolve('2001-02-29','12:00','UTC'));
assert.throws(()=>resolve('2000-01-01','24:00','UTC'));
assert.throws(()=>resolve('2000-01-01','12:00','Invented/Timezone'));
assert.deepEqual(coordinates('0','0'),{latitude:0,longitude:0});
assert.throws(()=>coordinates('','0'));
assert.throws(()=>coordinates('91','0'));
assert.throws(()=>coordinates('0','181'));
assert.throws(()=>coordinates('NaN','1'));
const berlin={name:'Berlin',latitude:52.52437,longitude:13.41053,timezone:'Europe/Berlin',country:'Germany'};
const places=placesFromResponse({results:[berlin,{...berlin,latitude:100},{...berlin,timezone:undefined}]});
assert.equal(places.length,1);assert.equal(places[0].timezone,'Europe/Berlin');
assert.deepEqual(placesFromResponse({}),[]);
assert.throws(()=>placesFromResponse({error:true}));
assert.throws(()=>placesFromResponse({results:'invalid'}));
console.log('Passed local birth-time resolution: DST gaps/folds, half-hour transitions, skipped dates, fractional offsets, date/coordinate validation, and place-response normalization.');
